# Cuts the rendered icon sheets into drawables and writes appfilter.xml / drawable.xml for the three plate flavors.
# Run from the repo root:  powershell -File assets/src/build-iconpack.ps1
# Sheets come from: assets/src/icons.html (see assets/README.md for the Edge commands).
Add-Type -AssemblyName System.Drawing
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$names = 'x','discord','youtube','messages','maps','phone','camera','browser','gallery','settings','clock','calendar','spotify','whatsapp','gmail','contacts','files','calc','notes','weather','store','wallet','torch','health','recorder','spyglass','basket','wagon','loaf','coins','proclamation','banner','tavern','dice','padlock','anvil','tower','book','dove','mask','brush','lantern','orb'
$sheets = Join-Path $root 'assets\icons\sheets'
$utf8 = New-Object System.Text.UTF8Encoding($false)

# mapping: emblem -> unique components (first use wins)
$seen = @{}; $rows = @()
foreach ($line in Get-Content (Join-Path $PSScriptRoot 'mapping.tsv')) {
  if ($line.StartsWith('#') -or $line.Trim() -eq '') { continue }
  $p = $line -split "`t"
  if ($p.Count -lt 2 -or -not $p[1].Contains('/')) { continue }
  if ($seen.ContainsKey($p[1])) { continue }
  $seen[$p[1]] = 1; $rows += ,@($p[0], $p[1])
}
Write-Output "mapped components: $($rows.Count)"

foreach ($flavor in 'heater','seal','bare') {
  $res = Join-Path $root "iconpack\pack\src\$flavor\res"
  $dr = Join-Path $res 'drawable-nodpi'; $xml = Join-Path $res 'xml'
  New-Item -ItemType Directory -Force $dr, $xml | Out-Null
  $sheet = [System.Drawing.Bitmap]::FromFile((Join-Path $sheets "$flavor.png"))
  for ($i = 0; $i -lt $names.Count; $i++) {
    $rect = New-Object System.Drawing.Rectangle(($i % 8) * 192), ([math]::Floor($i / 8) * 192), 192, 192
    $crop = $sheet.Clone($rect, $sheet.PixelFormat)
    $crop.Save((Join-Path $dr ("emblem_" + $names[$i] + ".png")), [System.Drawing.Imaging.ImageFormat]::Png)
    $crop.Dispose()
  }
  $sheet.Dispose()
  $hasBack = $flavor -ne 'bare'
  if ($hasBack) { Copy-Item (Join-Path $sheets "fallback-$flavor.png") (Join-Path $dr 'iconback_plate.png') -Force }

  $af = New-Object System.Text.StringBuilder
  [void]$af.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
  [void]$af.AppendLine('<!-- Generated by assets/src/build-iconpack.ps1 from assets/src/mapping.tsv. Do not edit by hand. -->')
  [void]$af.AppendLine('<resources>')
  if ($hasBack) {
    [void]$af.AppendLine('    <iconback img1="iconback_plate" />')
    [void]$af.AppendLine('    <scale factor="0.52" />')
  }
  foreach ($r in $rows) {
    [void]$af.AppendLine(('    <item component="ComponentInfo{{{0}}}" drawable="emblem_{1}" />' -f $r[1], $r[0]))
  }
  [void]$af.AppendLine('</resources>')
  [IO.File]::WriteAllText((Join-Path $xml 'appfilter.xml'), $af.ToString(), $utf8)

  $dx = New-Object System.Text.StringBuilder
  [void]$dx.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
  [void]$dx.AppendLine('<resources>')
  foreach ($n in $names) { [void]$dx.AppendLine(('    <item drawable="emblem_{0}" />' -f $n)) }
  [void]$dx.AppendLine('</resources>')
  [IO.File]::WriteAllText((Join-Path $xml 'drawable.xml'), $dx.ToString(), $utf8)
  Write-Output "$flavor done"
}
